import http from 'k6/http';
import { check, sleep } from 'k6';

/**
 * Task Create Load Test (NFR-PERF-01)
 * Target: < 250ms response time
 */
export const options = {
    stages: [
        { duration: '30s', target: 50 },
        { duration: '1m', target: 100 },
        { duration: '30s', target: 0 },
    ],
    thresholds: {
        http_req_duration: ['p(95)<300'],                      // NFR‑PERF‑02
        'http_req_duration{name:task_create}': ['p(95)<250'],  // NFR‑PERF‑01
        http_req_failed: ['rate<0.05'],  // allow slightly higher failure since we may create duplicates
    },
};

const BASE_URL = __ENV.BASE_URL || 'http://localhost:8080';

export function setup() {
    const loginRes = http.post(
        `${BASE_URL}/api/v1/auth/login`,
        JSON.stringify({ email: 'admin@taskhive.com', password: 'Admin@123' }),
        { headers: { 'Content-Type': 'application/json' } }
    );
    const body = JSON.parse(loginRes.body);
    return { token: body.data.accessToken };
}

export default function (data) {
    const uniqueSuffix = `${__VU}-${__ITER}-${Date.now()}`;

    const res = http.post(
        `${BASE_URL}/api/v1/tasks`,
        JSON.stringify({
            title: `k6 Load Test Task ${uniqueSuffix}`,
            description: 'Auto-generated by k6 load testing suite',
            priority: 'LOW',
            status: 'TODO',
        }),
        {
            headers: {
                'Content-Type': 'application/json',
                Authorization: `Bearer ${data.token}`,
            },
            tags: { name: 'task_create' },
        }
    );

    check(res, {
        'task create 201': (r) => r.status === 201,
        'task create < 250ms': (r) => r.timings.duration < 250,
    });

    sleep(1);
}
